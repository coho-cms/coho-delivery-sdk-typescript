import { CodegenError } from './model.ts';
import type { ContentType, Field, TypeModel } from './model.ts';

export interface GeneratedFile
{
  /** Relative to the output directory. */
  readonly path: string;
  readonly contents: string;
}

export interface Generated
{
  readonly files: readonly GeneratedFile[];
  /** Things to tell whoever ran the generator. Never fatal. */
  readonly warnings: readonly string[];
}

/**
 * Names the module defines or re-exports. A content type whose name would be one of
 * these is given `Entry` after it instead, so no project's types can shadow them.
 */
const RESERVED_TYPE_NAMES = new Set(['AnyEntry', 'Coho', 'Linked', 'Unresolved', 'RepeaterItem']);

/** The untyped reads on `Coho`. A content type with one of these slugs reads as `<slug>Type`. */
const RESERVED_MEMBERS = new Set(['bySlug', 'byId', 'byIds']);

/**
 * The TypeScript for a type model: one module, `index.ts`, holding an interface per
 * content type, their union, the shape the runtime hydrates with, the model's
 * source, and `createCoho`.
 *
 * A pure function of the model, so the same model always gives the same bytes and a
 * drift check can compare them. Nothing about the generator's own version is
 * written, for the same reason.
 */
export function generate(model: TypeModel): Generated
{
  const warnings: string[] = [];
  for (const warning of model.warnings ?? []) warnings.push(`${warning.type}.${warning.field}: ${warning.message}`);
  if (!model.source.immutable)
  {
    warnings.push(`Generated from '${model.source.ref}', a branch: its types can change. Release builds should name a tag.`);
  }

  const types = Object.keys(model.types).sort().map((slug) => model.types[slug] as ContentType);
  const names = interfaceNames(types, warnings);
  const nameOf = (slug: string): string => names.get(slug) ?? 'runtime.HydratedEntry';
  const usesRepeaters = types.some((type) => type.fields.some((field) => field.kind === 'repeater'));

  const out: string[] = [];
  out.push(...header(model));
  out.push('import * as runtime from "@coho-cms/delivery";');
  out.push('');
  out.push('export { isResolved } from "@coho-cms/delivery";');
  out.push('export type { Linked, Unresolved } from "@coho-cms/delivery";');
  out.push('');

  if (usesRepeaters)
  {
    out.push('/** An item of a repeater. Its own fields are not typed until component types are. */');
    out.push('export type RepeaterItem = { readonly _id: string; readonly [field: string]: unknown };');
    out.push('');
  }

  for (const type of types)
  {
    out.push(...interfaceFor(type, nameOf, warnings));
    out.push('');
  }

  out.push('/** Any content type on this ref. Switch on `_type` to narrow it. */');
  out.push(`export type AnyEntry = ${types.length === 0 ? 'never' : types.map((type) => nameOf(type.slug)).join(' | ')};`);
  out.push('');
  out.push(...shapeOf(types));
  out.push('');
  out.push(...sourceOf(model));
  out.push('');
  out.push(...client(types, nameOf, warnings));

  return { files: [{ path: 'index.ts', contents: `${out.join('\n')}\n` }], warnings };
}

function header(model: TypeModel): string[]
{
  const kind = model.source.immutable ? 'a tag' : 'a branch, whose types can change';
  return [
    '// Generated by @coho-cms/codegen from the Coho type model. Do not edit: run `coho-codegen generate`.',
    `// Project ${model.source.project}, ref ${model.source.ref} (${kind}), schema ${model.source.schemaHash}, type model ${model.irVersion}.`,
    '',
  ];
}

/** `blogPost` becomes `BlogPost`. Slugs start lowercase, so no two types share a name. */
function interfaceNames(types: readonly ContentType[], warnings: string[]): Map<string, string>
{
  const names = new Map<string, string>();
  const taken = new Set<string>();
  for (const type of types)
  {
    let name = type.slug.charAt(0).toUpperCase() + type.slug.slice(1);
    if (RESERVED_TYPE_NAMES.has(name))
    {
      warnings.push(`Type '${type.slug}' is named ${name}Entry, because ${name} is the generated module's own.`);
      name = `${name}Entry`;
    }
    if (taken.has(name)) throw new CodegenError(`Two types would both be named ${name}; rename one of them`);
    taken.add(name);
    names.set(type.slug, name);
  }
  return names;
}

function interfaceFor(type: ContentType, nameOf: (slug: string) => string, warnings: string[]): string[]
{
  const lines = [doc(type.name, ''), `export interface ${nameOf(type.slug)} extends runtime.EntryBase<${JSON.stringify(type.slug)}> {`];
  for (const field of type.fields)
  {
    lines.push(`  ${doc(field.name, note(field))}`);
    const optional = field.presence === 'always' ? '' : '?';
    lines.push(`  readonly ${field.id}${optional}: ${fieldType(type, field, nameOf, warnings)};`);
  }
  lines.push('}');
  return lines;
}

/** The TypeScript type of one field's value, following the type model's mapping rules. */
function fieldType(type: ContentType, field: Field, nameOf: (slug: string) => string, warnings: string[]): string
{
  switch (field.kind)
  {
    case 'text':
    case 'longText':
    case 'datetime':
      return 'string';
    case 'number':
    case 'integer':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'json':
      return 'unknown';
    case 'choice':
      return choices(field);
    case 'multichoice':
      return `readonly (${choices(field)})[]`;
    case 'reference': {
      // An empty `of` means the target's type is not on this ref: an untyped entry.
      const targets = field.of ?? [];
      const target = targets.length === 0 ? 'runtime.HydratedEntry' : targets.map(nameOf).join(' | ');
      return field.many ? `readonly runtime.Linked<${target}>[]` : `runtime.Linked<${target}>`;
    }
    case 'repeater':
      return 'readonly RepeaterItem[]';
    default:
      warnings.push(`${type.slug}.${field.id} is a '${field.kind}', which this generator does not know; it is typed unknown. Upgrade @coho-cms/codegen.`);
      return 'unknown';
  }
}

/**
 * A choice's values, and any other string: content may hold a value added after this
 * code was generated, and that must not stop it compiling against the new content.
 */
function choices(field: Field): string
{
  return [...(field.values ?? []).map((value) => JSON.stringify(value)), '(string & {})'].join(' | ');
}

function note(field: Field): string
{
  const notes: string[] = [];
  if (field.kind === 'longText' && field.textFormat === 'markdown') notes.push('Markdown.');
  if (field.kind === 'longText' && field.textFormat === 'html') notes.push('HTML.');
  if (field.kind === 'datetime') notes.push('An ISO 8601 date and time.');
  if (field.localized) notes.push('Absent where the locale has no translation.');
  return notes.join(' ');
}

/** A one-line doc comment. Names are content, so a comment's end inside one is broken up. */
function doc(name: string, note: string): string
{
  const text = [name.replace(/\s+/g, ' ').trim(), note].filter((part) => part !== '').join('. ').replace(/\*\//g, '*\\/');
  return `/** ${text} */`;
}

function shapeOf(types: readonly ContentType[]): string[]
{
  const lines = ['/** What the runtime needs to hydrate each type: its links, and the fields it always has. */', 'export const shape: runtime.Shape = {'];
  for (const type of types)
  {
    const links = type.fields
      .filter((field) => field.kind === 'reference')
      .map((field) => `${field.id}: ${JSON.stringify(field.many ? 'many' : 'one')}`);
    const always = type.fields.filter((field) => field.presence === 'always').map((field) => JSON.stringify(field.id));

    const parts: string[] = [];
    if (links.length > 0) parts.push(`links: { ${links.join(', ')} }`);
    if (always.length > 0) parts.push(`always: [${always.join(', ')}]`);
    lines.push(`  ${type.slug}: {${parts.length === 0 ? '' : ` ${parts.join(', ')} `}},`);
  }
  lines.push('};');
  return lines;
}

function sourceOf(model: TypeModel): string[]
{
  return [
    '/** Where these types came from, for reporting which release a build was made from. */',
    'export const source = {',
    `  project: ${JSON.stringify(model.source.project)},`,
    `  ref: ${JSON.stringify(model.source.ref)},`,
    `  immutable: ${model.source.immutable},`,
    `  schemaHash: ${JSON.stringify(model.source.schemaHash)},`,
    `  irVersion: ${JSON.stringify(model.irVersion)},`,
    '} as const;',
  ];
}

function client(types: readonly ContentType[], nameOf: (slug: string) => string, warnings: string[]): string[]
{
  const members = new Set<string>();
  const readers = types.map((type) =>
  {
    let member = type.slug;
    if (RESERVED_MEMBERS.has(member))
    {
      warnings.push(`Type '${type.slug}' is read as coho.${member}Type, because coho.${member} is the untyped read.`);
      member = `${member}Type`;
    }
    if (members.has(member)) throw new CodegenError(`Two types would both be read as coho.${member}; rename one of them`);
    members.add(member);
    const sortable = type.fields.filter((field) => field.sortable).map((field) => JSON.stringify(field.id));
    const generic = `${nameOf(type.slug)}, ${sortable.length === 0 ? 'never' : sortable.join(' | ')}`;
    return { type, member, generic };
  });

  const lines = ['/** Typed reads of every content type, on the ref and in the locale the config names. */', 'export interface Coho {'];
  for (const { type, member, generic } of readers)
  {
    lines.push(`  ${doc(type.name, '')}`);
    lines.push(`  readonly ${member}: runtime.TypeReader<${generic}>;`);
  }
  lines.push(
    '  /** The entry with this slug, whatever its type, or null. */',
    '  bySlug(slug: string, options?: runtime.ReadOptions): Promise<AnyEntry | null>;',
    '  /** The entry with this id, whatever its type, or null. */',
    '  byId(id: string, options?: runtime.ReadOptions): Promise<AnyEntry | null>;',
    '  /** The entries that exist, sorted by id. Ids not on the ref are left out. */',
    '  byIds(ids: readonly string[], options?: runtime.ReadOptions): Promise<AnyEntry[]>;',
    '}',
    '',
    '/** A client for these types. The delivery key comes from the app; this library reads no environment. */',
    'export function createCoho(config: runtime.ContentConfig): Coho {',
    '  const content = runtime.createContentClient<AnyEntry>(config, shape);',
    '  return {',
  );
  for (const { type, member, generic } of readers)
  {
    lines.push(`    ${member}: content.type<${generic}>(${JSON.stringify(type.slug)}),`);
  }
  lines.push('    bySlug: content.bySlug,', '    byId: content.byId,', '    byIds: content.byIds,', '  };', '}');
  return lines;
}
